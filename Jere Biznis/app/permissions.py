OWNER="INSTITUTION_OWNER"
BACKUP_ADMIN="BACKUP_ADMIN"
OWNER_PERMISSIONS={
"DATABASE_OWNER","DATABASE_CREATE","DATABASE_READ","DATABASE_UPDATE","DATABASE_DELETE",
"DATABASE_CRUD","DATABASE_BACKUP","DATABASE_RESTORE","DATABASE_EXPORT","DATABASE_IMPORT",
"USER_MANAGEMENT","ROLE_MANAGEMENT","PERMISSION_MANAGEMENT","DEVICE_MANAGEMENT",
"SYNC_MANAGEMENT","AUDIT_READ","AUDIT_MANAGEMENT","SUBSCRIPTION_READ",
"SUBSCRIPTION_MANAGEMENT","GKACH_PAYMENT"}
BACKUP_PERMISSIONS={"DATABASE_BACKUP","AUDIT_READ"}
def can(role, permission):
    if role == OWNER: return permission in OWNER_PERMISSIONS
    if role == BACKUP_ADMIN: return permission in BACKUP_PERMISSIONS
    return False

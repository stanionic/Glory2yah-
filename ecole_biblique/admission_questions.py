def get_questions_for_document(document_name):
    """Return all questions for a specific document."""
    return [q for q in ADMISSION_QUESTIONS if q["document"] == document_name]

def get_all_documents():
    """Return list of all unique document names."""
    docs = set()
    for q in ADMISSION_QUESTIONS:
        docs.add(q["document"])
    return sorted(list(docs))

def get_question_by_id(qid):
    """Return a question by its ID."""
    for q in ADMISSION_QUESTIONS:
        if q["id"] == qid:
            return q
    return None
